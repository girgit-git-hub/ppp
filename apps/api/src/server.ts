import Fastify from 'fastify';
import cors from '@fastify/cors';
import multipart from '@fastify/multipart';
import fastifyStatic from '@fastify/static';
import path from 'node:path';
import {env} from './config/env.js';
import {taskRoutes} from './routes/tasks.js';
import {evidenceRoutes} from './routes/evidence.js';
import {payoutRoutes} from './routes/payouts.js';
import {webhookRoutes} from './routes/webhooks.js';
import {agentRoutes} from './routes/agent.js';
import {paypalRoutes} from './routes/paypal.js';
const app=Fastify({logger:true});
const allowList=env.WEB_ORIGIN.split(',').map(s=>s.trim()).filter(Boolean);
await app.register(cors,{origin:(origin,cb)=>cb(null,!origin || allowList.includes(origin))});
await app.register(multipart,{limits:{fileSize:10*1024*1024}});
await app.register(fastifyStatic,{root:path.resolve('uploads'),prefix:'/uploads/',decorateReply:false});
app.get('/api/health',async()=>({ok:true,service:'proofpay-api',aiProvider:env.AI_PROVIDER}));
await taskRoutes(app); await evidenceRoutes(app); await payoutRoutes(app);
await webhookRoutes(app); await agentRoutes(app); await paypalRoutes(app);
await app.listen({port:Number(process.env.PORT || env.API_PORT),host:'0.0.0.0'});
